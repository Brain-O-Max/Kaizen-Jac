// Builds one (or all) of the sites as a folder you can upload to shared hosting (cPanel) without Node.js:
//
//   npm run package:enterprise      -> deploy/enterprise/  and deploy/enterprise.zip
//   npm run package:all             -> all three
//
// The folder holds the static website (Next.js export), the PHP backend in api/, the original photos in uploads/,
// and an empty _data/ for saved content and inquiries. Settings are read from .env.production.local (see README).
import { spawnSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const { loadEnvConfig } = require('@next/env');
loadEnvConfig(root, false);

const SITES = {
  enterprise: 'Kaizen Enterprise',
  design: 'Kaizen Design & Development',
  training: 'Kaizen Training Center',
};

const arg = process.argv[2];
const targets = arg === 'all' ? Object.keys(SITES) : [arg];
if (!targets.every((s) => s in SITES)) {
  console.error(`Usage: node scripts/package.mjs <${Object.keys(SITES).join('|')}|all>`);
  process.exit(1);
}

const setting = (name, site) => (process.env[`${name}_${site.toUpperCase()}`] || process.env[name] || '').trim();
const phpString = (value) => `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const copyDir = (from, to) => fs.existsSync(from) && fs.cpSync(from, to, { recursive: true });

function packageSite(site) {
  const password = setting('ADMIN_PASSWORD', site);
  if (!password || password === 'change-me') {
    throw new Error(`Set ADMIN_PASSWORD_${site.toUpperCase()} (or ADMIN_PASSWORD) in .env.production.local first.`);
  }
  const missingUrls = ['SITE_URL_ENTERPRISE', 'SITE_URL_DESIGN', 'SITE_URL_TRAINING'].filter((k) => !process.env[k]);
  if (missingUrls.length) console.warn(`! ${missingUrls.join(', ')} not set: footer links and SEO will point to localhost.`);

  console.log(`\n=== Building ${SITES[site]} (SITE=${site})`);
  // With output: 'export' Next.js writes the finished static site into distDir.
  const distDir = `.next-build-${site}`;
  fs.rmSync(path.join(root, distDir), { recursive: true, force: true });
  const build = spawnSync(process.execPath, [require.resolve('next/dist/bin/next'), 'build'], {
    cwd: root,
    stdio: 'inherit',
    env: { ...process.env, SITE: site, NEXT_DIST_DIR: distDir, NODE_ENV: 'production' },
  });
  if (build.status !== 0) throw new Error(`next build failed for ${site}`);

  const out = path.join(root, 'deploy', site);
  fs.rmSync(out, { recursive: true, force: true });
  fs.cpSync(path.join(root, distDir), out, { recursive: true });

  // PHP backend + settings.
  fs.cpSync(path.join(root, 'php', 'api'), path.join(out, 'api'), { recursive: true });
  const salt = crypto.randomBytes(16);
  const iterations = 100000;
  const hash = crypto.pbkdf2Sync(password, salt, iterations, 32, 'sha256').toString('hex');
  const seedFiles = fs.readdirSync(path.join(root, 'seed-uploads'));
  const inquiryEmail = setting('INQUIRY_EMAIL', site);
  fs.writeFileSync(
    path.join(out, 'api', 'config.php'),
    `<?php
// Generated by \`npm run package:${site}\`. Re-run that script to change the password, then upload this file again.
if (!defined('KAIZEN')) { http_response_code(404); exit; }
return [
    'site' => ${phpString(site)},
    'site_name' => ${phpString(SITES[site])},
    'password_hash' => ${phpString(`pbkdf2_sha256$${iterations}$${salt.toString('hex')}$${hash}`)},
    // Where contact-form inquiries are emailed. Empty = the contact email saved in the admin.
    'inquiry_email' => ${phpString(inquiryEmail)},
    'seed_files' => [${seedFiles.map(phpString).join(', ')}],
];
`
  );

  // Uploads: the original photos plus anything uploaded locally (content saved locally may point to them).
  // Uploading these never overwrites files added in the online admin, which get unique names.
  fs.mkdirSync(path.join(out, 'uploads'), { recursive: true });
  copyDir(path.join(root, 'seed-uploads'), path.join(out, 'uploads'));
  copyDir(path.join(root, 'storage', site, 'uploads'), path.join(out, 'uploads'));
  fs.copyFileSync(path.join(root, 'php', 'uploads.htaccess'), path.join(out, 'uploads', '.htaccess'));

  // Private data folder. Deliberately no content.json, so re-uploading never wipes edits made online.
  fs.mkdirSync(path.join(out, '_data'), { recursive: true });
  fs.copyFileSync(path.join(root, 'php', 'data.htaccess'), path.join(out, '_data', '.htaccess'));
  fs.copyFileSync(path.join(root, 'php', 'root.htaccess'), path.join(out, '.htaccess'));

  // Zip for cPanel's File Manager (Upload, then Extract). Windows 10+ and macOS tar can write zip files.
  const zip = path.join(root, 'deploy', `${site}.zip`);
  fs.rmSync(zip, { force: true });
  // On Windows prefer the built-in bsdtar over a GNU tar from Git Bash, which cannot write zip files.
  const winTar = path.join(process.env.SystemRoot || 'C:\\Windows', 'System32', 'tar.exe');
  const tar = process.platform === 'win32' && fs.existsSync(winTar) ? winTar : 'tar';
  const zipped = spawnSync(tar,['-a', '-c', '-f', zip, '-C', out, '.'], { stdio: 'ignore' });
  const zipOk = zipped.status === 0 && fs.existsSync(zip) && fs.readFileSync(zip).subarray(0, 2).toString() === 'PK';
  if (!zipOk) fs.rmSync(zip, { force: true });

  console.log(`\n✓ ${SITES[site]} packaged in deploy/${site}/${zipOk ? ` and deploy/${site}.zip` : ' (zip it yourself: no zip-capable tar found)'}`);
  if (!inquiryEmail) console.log('  Inquiries will be emailed to the contact email saved in the admin (set INQUIRY_EMAIL to override).');
}

try {
  for (const site of targets) packageSite(site);
} catch (err) {
  console.error(`\n✗ ${err.message}`);
  process.exit(1);
}
